step_install_cert_manager() {
    echo ""
    echo "=== Installing cert-manager ==="
    local version
    version=$(cd "${OPERATOR_DIR}" && go list -m -f '{{.Version}}' github.com/cert-manager/cert-manager)
    echo "cert-manager version: ${version}"
    oc apply -f "https://github.com/cert-manager/cert-manager/releases/download/${version}/cert-manager.yaml"
    echo "Waiting for cert-manager to be ready..."
    oc wait --for=condition=Available deployment/cert-manager -n cert-manager --timeout=120s
    oc wait --for=condition=Available deployment/cert-manager-webhook -n cert-manager --timeout=120s
    oc wait --for=condition=Available deployment/cert-manager-cainjector -n cert-manager --timeout=120s
    echo "Waiting for cert-manager webhook to accept requests..."
    until oc apply --dry-run=server -n cert-manager -f - <<'PROBE' 2>/dev/null
apiVersion: cert-manager.io/v1
kind: Issuer
metadata:
  name: probe
spec:
  selfSigned: {}
PROBE
    do sleep 3; done
    oc delete issuer probe -n cert-manager --ignore-not-found 2>/dev/null
}

step_generate_manifests() {
    echo ""
    echo "=== Generating manifests ==="
    # Subshell: a bare cd would also move the caller's shell under
    # --source-only, and every other step uses absolute paths anyway.
    (
        cd "${OPERATOR_DIR}"
        # The manifests target already depends on trusted-cluster-gen.
        make REGISTRY="${REGISTRY}" TAG="${TAG}" NAMESPACE="${NAMESPACE}" \
             APPROVED_IMAGE="${APPROVED_IMAGE}" manifests
    )
}

step_create_machineconfig_pool() {
    echo ""
    echo "=== Creating MachineConfig and MachineConfigPool ==="
    MC_NAME="99-${MACHINESET_NAME}"

    oc apply -f - <<EOF
apiVersion: machineconfiguration.openshift.io/v1
kind: MachineConfig
metadata:
  name: ${MC_NAME}
  labels:
    machineconfiguration.openshift.io/role: ${MACHINESET_NAME}
    machine.openshift.io/cluster-api-machineset: ${MACHINESET_NAME}
spec:
  osImageURL: ${APPROVED_IMAGE}
---
apiVersion: machineconfiguration.openshift.io/v1
kind: MachineConfigPool
metadata:
  name: ${MACHINESET_NAME}
spec:
  machineConfigSelector:
    matchExpressions:
      - key: machineconfiguration.openshift.io/role
        operator: In
        values:
          - worker
          - ${MACHINESET_NAME}
  nodeSelector:
    matchLabels:
      node-role.kubernetes.io/${MACHINESET_NAME}: ""
EOF

    echo "Waiting for MachineConfigPool to include ${MC_NAME}..."
    until oc get mcp "${MACHINESET_NAME}" -o jsonpath='{.status.configuration.source[*].name}' 2>/dev/null | grep -q "${MC_NAME}"; do
        sleep 5
    done
    echo "  MachineConfig included in pool"

    echo "Waiting for MachineConfigPool to report Updated=True..."
    until oc get mcp "${MACHINESET_NAME}" -o jsonpath='{.status.conditions[?(@.type=="Updated")].status}' 2>/dev/null | grep -q "True"; do
        sleep 5
    done
    echo "  MachineConfigPool is Updated"
}

step_create_namespace_and_scc() {
    echo ""
    echo "=== Creating namespace and SCC ==="
    oc create namespace "${NAMESPACE}" 2>/dev/null || true
    sed "s/<NAMESPACE>/${NAMESPACE}/g" "${CONFIG_DIR}/openshift/scc.yaml" | oc apply -f -
}

step_apply_crds() {
    echo ""
    echo "=== Applying CRDs ==="
    local crd
    local crds=()
    for crd in trusted-execution-clusters.io_trustedexecutionclusters \
               trusted-execution-clusters.io_machines \
               trusted-execution-clusters.io_approvedimages \
               trusted-execution-clusters.io_attestationkeys \
               cert-manager.io_issuers \
               cert-manager.io_certificates; do
        crds+=("${CONFIG_DIR}/crd/${crd}.yaml")
    done
    require_generated_manifests "${crds[@]}"

    for crd in "${crds[@]}"; do
        oc apply --server-side --force-conflicts -f "${crd}"
    done
}

step_apply_rbac() {
    echo ""
    echo "=== Applying RBAC ==="
    # role.yaml is the only generated file here; the rest of config/rbac is
    # checked in, and kustomization.yaml.in overwrites the generated one.
    require_generated_manifests "${CONFIG_DIR}/rbac/role.yaml"

    local rbac_tmp
    rbac_tmp=$(mktemp -d)
    cp -r "${CONFIG_DIR}"/rbac/* "${rbac_tmp}/"

    sed -i "s/namespace: system/namespace: ${NAMESPACE}/g" "${rbac_tmp}/service_account.yaml"
    sed -i "s/name: trusted-cluster-operator-role/name: ${NAMESPACE}-trusted-cluster-operator-role/g" "${rbac_tmp}/role.yaml"
    sed -i "s/name: manager-rolebinding/name: ${NAMESPACE}-manager-rolebinding/g; \
            s/name: trusted-cluster-operator-role/name: ${NAMESPACE}-trusted-cluster-operator-role/g; \
            s/namespace: system/namespace: ${NAMESPACE}/g" "${rbac_tmp}/role_binding.yaml"
    sed -i "s/namespace: system/namespace: ${NAMESPACE}/g" "${rbac_tmp}/leader_election_role.yaml"
    sed -i "s/namespace: system/namespace: ${NAMESPACE}/g" "${rbac_tmp}/leader_election_role_binding.yaml"

    cp "${CONFIG_DIR}/rbac/kustomization.yaml.in" "${rbac_tmp}/kustomization.yaml"
    sed -i "s/namespace: NAMESPACE/namespace: ${NAMESPACE}/g" "${rbac_tmp}/kustomization.yaml"
    cp "${CONFIG_DIR}/openshift/scc.yaml" "${rbac_tmp}/scc.yaml"
    sed -i "s/<NAMESPACE>/${NAMESPACE}/g" "${rbac_tmp}/scc.yaml"
    echo "  - scc.yaml" >> "${rbac_tmp}/kustomization.yaml"

    oc apply --server-side --force-conflicts -k "${rbac_tmp}"
    rm -rf "${rbac_tmp}"
}

step_deploy_operator() {
    echo ""
    echo "=== Deploying operator ==="
    require_generated_manifests "${CONFIG_DIR}/deploy/operator.yaml"

    oc apply -f "${CONFIG_DIR}/deploy/operator.yaml"
    echo "Waiting for operator deployment..."
    oc wait --for=condition=Available deployment/trusted-cluster-operator \
        -n "${NAMESPACE}" --timeout=300s
}

step_setup_tls_certificates() {
    echo ""
    echo "=== Setting up TLS CA chain ==="

    oc apply -n "${NAMESPACE}" -f - <<EOF
apiVersion: cert-manager.io/v1
kind: Issuer
metadata:
  name: root-issuer
spec:
  selfSigned: {}
---
apiVersion: cert-manager.io/v1
kind: Certificate
metadata:
  name: root-cert
spec:
  secretName: root-secret
  isCA: true
  commonName: selfsigned-ca
  issuerRef:
    name: root-issuer
---
apiVersion: cert-manager.io/v1
kind: Issuer
metadata:
  name: issuer
spec:
  ca:
    secretName: root-secret
EOF

    echo "Waiting for root CA secret..."
    until oc get secret root-secret -n "${NAMESPACE}" &>/dev/null; do sleep 2; done

    for pair in "reg-srv-cert:reg-srv-secret:register-server" \
                "trustee-cert:trustee-secret:kbs-service" \
                "att-reg-cert:att-reg-secret:attestation-key-register"; do
        IFS=: read -r cert_name secret_name svc_name <<< "${pair}"
        oc apply -n "${NAMESPACE}" -f - <<EOF
apiVersion: cert-manager.io/v1
kind: Certificate
metadata:
  name: ${cert_name}
spec:
  secretName: ${secret_name}
  dnsNames:
    - ${svc_name}.${NAMESPACE}.svc
  issuerRef:
    name: issuer
EOF
    done

    echo "Waiting for TLS secrets..."
    for secret in reg-srv-secret trustee-secret att-reg-secret; do
        until oc get secret "${secret}" -n "${NAMESPACE}" &>/dev/null; do sleep 2; done
        echo "  ${secret} ready"
    done
}

step_expose_services() {
    echo ""
    echo "=== Pre-creating services as LoadBalancer ==="

    for pair in "kbs-service:8080:kbs" "register-server:8000:register-server" "attestation-key-register:8001:attestation-key-register"; do
        IFS=: read -r svc_name svc_port app_label <<< "${pair}"
        oc apply -n "${NAMESPACE}" -f - <<EOF
apiVersion: v1
kind: Service
metadata:
  name: ${svc_name}
spec:
  type: LoadBalancer
  selector:
    app: ${app_label}
  ports:
    - port: ${svc_port}
      targetPort: ${svc_port}
EOF
    done

    for svc in kbs-service register-server attestation-key-register; do
        LB_ADDRS[${svc}]=$(get_lb_address "${svc}")
    done
}

step_issue_lb_certificates() {
    echo ""
    echo "=== Issuing certificates for LoadBalancer addresses ==="

    for pair in "reg-srv-cert:reg-srv-secret:register-server" \
                "trustee-cert:trustee-secret:kbs-service" \
                "att-reg-cert:att-reg-secret:attestation-key-register"; do
        IFS=: read -r cert_name secret_name svc_name <<< "${pair}"
        local lb_addr="${LB_ADDRS[${svc_name}]}"
        local ip_field="" dns_field=""

        if [[ "${lb_addr}" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
            ip_field="ipAddresses: [\"${lb_addr}\"]"
        else
            dns_field="dnsNames: [\"${lb_addr}\"]"
        fi

        oc apply -n "${NAMESPACE}" -f - <<EOF
apiVersion: cert-manager.io/v1
kind: Certificate
metadata:
  name: ${cert_name}
spec:
  secretName: ${secret_name}
  ${dns_field}
  ${ip_field}
  issuerRef:
    name: issuer
EOF
    done

    echo "Waiting for TLS secrets..."
    for secret in reg-srv-secret trustee-secret att-reg-secret; do
        until oc get secret "${secret}" -n "${NAMESPACE}" &>/dev/null; do sleep 2; done
        echo "  ${secret} ready"
    done
}

step_create_tec_cr() {
    echo ""
    echo "=== Creating TrustedExecutionCluster CR ==="
    require_generated_manifests "${CONFIG_DIR}/deploy/approved_image_cr_*.yaml"

    TRUSTEE_LB="${LB_ADDRS[kbs-service]}"
    TRUSTEE_ADDR="${TRUSTEE_LB}:8080"

    oc apply -n "${NAMESPACE}" -f - <<EOF
apiVersion: trusted-execution-clusters.io/v1alpha1
kind: TrustedExecutionCluster
metadata:
  name: trusted-execution-cluster
  namespace: ${NAMESPACE}
spec:
  publicTrusteeAddr: ${TRUSTEE_ADDR}
  registerServerPort: 8000
  trusteeKbsPort: 8080
  trusteeSecret: trustee-secret
  registerServerSecret: reg-srv-secret
  attestationKeyRegisterSecret: att-reg-secret
EOF

    echo "Applying ApprovedImage..."
    oc apply -f "${CONFIG_DIR}"/deploy/approved_image_cr_*.yaml

    echo "Waiting for operator-managed deployments..."
    for depl in trustee-deployment register-server attestation-key-register; do
        echo "  waiting for ${depl}..."
        until oc get deployment "${depl}" -n "${NAMESPACE}" &>/dev/null; do sleep 2; done
        oc wait --for=condition=Available "deployment/${depl}" -n "${NAMESPACE}" --timeout=300s
    done

    echo "Waiting for ApprovedImage to be committed..."
    local approved_name
    approved_name=$(oc get approvedimages -n "${NAMESPACE}" -o jsonpath='{.items[0].metadata.name}')
    echo "  Found ApprovedImage: ${approved_name}"
    oc wait --for=condition=Committed "approvedimage/${approved_name}" -n "${NAMESPACE}" --timeout=300s

    echo "Waiting for TrustedExecutionCluster to be installed..."
    oc wait --for=condition=Installed trustedexecutioncluster/trusted-execution-cluster \
        -n "${NAMESPACE}" --timeout=300s
}

step_create_ignition_secret() {
    echo ""
    echo "=== Creating ignition secret from MCO-managed user data ==="

    REG_SERVER_LB="${LB_ADDRS[register-server]}"
    REGISTRATION_SERVER="${REG_SERVER_LB}:8000"
    MANAGED_SECRET="${MACHINESET_NAME}-user-data-managed"
    IGNITION_SECRET="${MANAGED_SECRET}-cocl"

    echo "Waiting for MCO to create ${MANAGED_SECRET}..."
    until oc get secret "${MANAGED_SECRET}" -n "${MACHINE_API_NS}" &>/dev/null; do
        sleep 5
    done
    echo "  ${MANAGED_SECRET} ready"

    echo "Creating extended ignition secret with register-server URL and CA..."
    local root_ca_pem root_ca_encoded
    root_ca_pem=$(oc get secret root-secret -n "${NAMESPACE}" -o jsonpath='{.data.ca\.crt}' | base64 -d)
    root_ca_encoded=$(python3 -c "
import sys
data = sys.stdin.buffer.read()
print(''.join(chr(b) if chr(b).isascii() and chr(b).isalnum() else f'%{b:02X}' for b in data), end='')
" <<< "${root_ca_pem}")

    if oc get secret "${IGNITION_SECRET}" -n "${MACHINE_API_NS}" &>/dev/null; then
        oc delete secret "${IGNITION_SECRET}" -n "${MACHINE_API_NS}"
    fi

    local ignition_file
    ignition_file=$(mktemp)
    oc get secret "${MANAGED_SECRET}" -n "${MACHINE_API_NS}" -o jsonpath='{.data.userData}' \
      | base64 -d \
      | jq --arg url "https://${REGISTRATION_SERVER}/ignition-clevis-pin-trustee" \
           --arg ca "data:,${root_ca_encoded}" \
        '
          .ignition.version = "3.6.0" |
          .ignition.config.merge += [{"source": $url}] |
          .ignition.security.tls.certificateAuthorities += [{"source": $ca}]
        ' > "${ignition_file}"

    oc create secret generic "${IGNITION_SECRET}" -n "${MACHINE_API_NS}" \
        --from-file=userData="${ignition_file}"
    rm -f "${ignition_file}"
    echo "  Ignition secret ${IGNITION_SECRET} created"
}

step_create_machineset() {
    echo ""
    echo "=== Creating confidential machineset ==="

    if ! oc get machineset "${SOURCE_MACHINESET}" -n "${MACHINE_API_NS}" &>/dev/null; then
        echo "Error: source machineset '${SOURCE_MACHINESET}' not found"
        exit 1
    fi

    local machineset_file="${OUTPUT_DIR}/${MACHINESET_NAME}.yaml"
    mkdir -p "${OUTPUT_DIR}"

    oc get machineset "${SOURCE_MACHINESET}" -n "${MACHINE_API_NS}" -o json | \
      jq --arg new_name "${MACHINESET_NAME}" \
         --arg vm_size "${VM_SIZE}" \
         --arg image "${VHD_RESOURCE_ID}" \
         --arg user_data "${IGNITION_SECRET}" \
         --arg exclude_label "${BOOT_IMAGE_EXCLUDE_LABEL}" \
         --argjson replicas "${REPLICAS}" \
      '
      del(.metadata.uid, .metadata.resourceVersion, .metadata.creationTimestamp, .metadata.generation, .metadata.managedFields, .status) |
      .metadata.name = $new_name |
      .metadata.namespace = "openshift-machine-api" |
      .metadata.labels["machine.openshift.io/cluster-api-machineset"] = $new_name |
      .metadata.labels[$exclude_label] = "true" |
      .spec.replicas = $replicas |
      .spec.selector.matchLabels["machine.openshift.io/cluster-api-machineset"] = $new_name |
      .spec.template.metadata.labels["machine.openshift.io/cluster-api-machineset"] = $new_name |
      .spec.template.spec.metadata.labels["node-role.kubernetes.io/" + $new_name] = "" |
      .spec.template.spec.providerSpec.value.acceleratedNetworking = false |
      .spec.template.spec.providerSpec.value.image = {"resourceID": $image} |
      .spec.template.spec.providerSpec.value.vmSize = $vm_size |
      .spec.template.spec.providerSpec.value.userDataSecret.name = $user_data |
      .spec.template.spec.providerSpec.value.osDisk.managedDisk.securityProfile.securityEncryptionType = "VMGuestStateOnly" |
      .spec.template.spec.providerSpec.value.securityProfile = {
        "settings": {
          "confidentialVM": {
            "uefiSettings": {
              "secureBoot": "Enabled",
              "virtualizedTrustedPlatformModule": "Enabled"
            }
          },
          "securityType": "ConfidentialVM"
        }
      }
      ' | yq -P > "${machineset_file}"

    oc apply -f "${machineset_file}"

    echo ""
    echo "=== Installation complete ==="
    echo "  Namespace:    ${NAMESPACE}"
    echo "  Machineset:   ${MACHINESET_NAME} (${REPLICAS} replica(s))"
    echo "  Manifest:     ${machineset_file}"
    echo "  Trustee:      https://${TRUSTEE_ADDR}"
    echo "  Reg server:   https://${REGISTRATION_SERVER}"
    echo "  KBS LB IP:    ${TRUSTEE_LB}"
    echo "  RegSrv LB IP: ${REG_SERVER_LB}"
    echo "  User data:    ${IGNITION_SECRET}"
    echo ""
    echo "Monitor node boot progress with:"
    echo "  oc get machines -n openshift-machine-api -l machine.openshift.io/cluster-api-machineset=${MACHINESET_NAME} -w"
}

# ---------------------------------------------------------------------------
# Tell the MCO to keep its hands off the confidential nodes' boot image.
#
# Confidential nodes boot a custom RHCOS image, which collides with two
# independent MCO features:
#
#   * managedBootImages - the boot image controller rewrites the boot image
#     reference of the MachineSets it manages. Left alone, it would replace
#     the custom VHD with the stock RHCOS image, so machines scaled up later
#     boot an image that cannot be attested. The confidential machineset is
#     therefore excluded with a Partial selector: every machineset *without*
#     the exclusion label stays managed, the labelled one opts out.
#
#   * bootImageSkewEnforcement - compares the RHCOS version a node booted
#     from against the cluster version and sets Upgradeable=False when the
#     skew is too large, which blocks minor version upgrades. The custom
#     image carries a version the MCO cannot reason about. This is a
#     cluster-wide switch (no per-pool granularity), so enforcement is turned
#     off entirely with mode "None".
#
# Both fields are version and platform dependent, so each one is probed first
# and verified afterwards instead of being patched blindly. Everything here
# is idempotent and safe to re-run.
# ---------------------------------------------------------------------------

# Label an existing machineset so the boot image controller skips it.
# Done *before* the Partial selector is applied: the other way round would
# briefly place the machineset under MCO management.
#
# On a first install the machineset does not exist yet and this is a no-op:
# step_create_machineset applies BOOT_IMAGE_EXCLUDE_LABEL at creation time.
# It does the work when the machineset was created by other means, or when
# the installer re-runs against a cluster that already has one.
label_machineset() {
    if ! oc get machineset "${MACHINESET_NAME}" -n "${MACHINE_API_NS}" &>/dev/null; then
        echo "  Machineset '${MACHINESET_NAME}' does not exist yet, it will be labelled at creation"
        return 0
    fi

    oc label machineset "${MACHINESET_NAME}" -n "${MACHINE_API_NS}" \
        --overwrite "${BOOT_IMAGE_EXCLUDE_LABEL}=true"
}

# Exclude labelled machinesets from MCO-managed boot image updates.
configure_managed_boot_images() {
    local existing patch out mode

    # Keep any machineManagers entry for other resources (e.g.
    # controlplanemachinesets) and only replace the machinesets one: a merge
    # patch overwrites the whole list.
    existing=$(oc get "${MACHINE_CONFIGURATION}" cluster -o json |
        jq -c '.spec.managedBootImages.machineManagers // []')

    patch=$(jq -nc --argjson existing "${existing}" --arg label "${BOOT_IMAGE_EXCLUDE_LABEL}" '
      {
        spec: {
          managedBootImages: {
            machineManagers: (
              [ $existing[]
                | select((.resource != "machinesets") or (.apiGroup != "machine.openshift.io")) ]
              + [ {
                    resource: "machinesets",
                    apiGroup: "machine.openshift.io",
                    selection: {
                      mode: "Partial",
                      partial: {
                        machineResourceSelector: {
                          matchExpressions: [ { key: $label, operator: "DoesNotExist" } ]
                        }
                      }
                    }
                  } ]
            )
          }
        }
      }')

    if ! out=$(oc patch "${MACHINE_CONFIGURATION}" cluster --type=merge -p "${patch}" 2>&1); then
        # On platforms the boot image controller does not support, the
        # managed-bootimages-platform-check ValidatingAdmissionPolicy rejects
        # the patch. Nothing updates boot images there, so this is harmless.
        if grep -qi 'only supported on these platforms' <<<"${out}"; then
            echo "  Boot image updates are not supported on this platform - nothing to opt out of."
            echo "    ${out}"
            return 0
        fi
        echo "  Error: failed to patch managedBootImages: ${out}" >&2
        return 1
    fi

    mode=$(oc get "${MACHINE_CONFIGURATION}" cluster -o jsonpath="{.spec.managedBootImages.machineManagers[?(@.resource=='machinesets')].selection.mode}")
    if [[ "${mode}" != "Partial" ]]; then
        echo "  Error: managedBootImages selection mode is '${mode:-<empty>}', expected 'Partial'" >&2
        return 1
    fi
    echo "  managedBootImages: machinesets labelled '${BOOT_IMAGE_EXCLUDE_LABEL}' are excluded from boot image updates"
}

# Disable boot image skew enforcement (cluster-wide; the custom RHCOS image
# carries a version the MCO cannot compare against the cluster version).
configure_boot_image_skew_enforcement() {
    local supported mode status_mode

    supported=$(oc get crd "${MACHINE_CONFIGURATION}" -o json 2>/dev/null |
        jq -r '[ .spec.versions[]
                 | select(.name == "v1")
                 | (.schema.openAPIV3Schema.properties.spec.properties // {})
                 | has("bootImageSkewEnforcement") ] | any' || true)

    if [[ "${supported}" != "true" ]]; then
        # Older clusters prune the unknown field without error, so patching
        # would silently do nothing. Nothing enforces skew there either.
        echo "  bootImageSkewEnforcement is not present in this cluster's API - skipping (no skew enforcement to disable)."
        return 0
    fi

    oc patch "${MACHINE_CONFIGURATION}" cluster --type=merge \
        -p '{"spec":{"bootImageSkewEnforcement":{"mode":"None"}}}'

    mode=$(oc get "${MACHINE_CONFIGURATION}" cluster -o jsonpath='{.spec.bootImageSkewEnforcement.mode}')
    if [[ "${mode}" != "None" ]]; then
        echo "  Error: spec.bootImageSkewEnforcement.mode is '${mode:-<empty>}', expected 'None'" >&2
        return 1
    fi

    echo "  bootImageSkewEnforcement: disabled (mode=None)"

    # The MCO mirrors the accepted config into status; wait briefly so a
    # rejected value does not go unnoticed.
    status_mode=""
    for _ in $(seq 1 12); do
        status_mode=$(oc get "${MACHINE_CONFIGURATION}" cluster -o jsonpath='{.status.bootImageSkewEnforcementStatus.mode}' 2>/dev/null || true)
        if [[ "${status_mode}" == "None" ]]; then
            break
        fi
        sleep 5
    done
    if [[ "${status_mode}" == "None" ]]; then
        echo "  MCO acknowledged skew enforcement mode None"
    else
        echo "  Warning: status.bootImageSkewEnforcementStatus.mode is '${status_mode:-<empty>}', expected 'None'" >&2
    fi
    echo "  Note: skew enforcement is cluster-wide; the MCCBootImageSkewEnforcementNone alert is expected to fire."
}

step_configure_boot_image_management() {
    echo ""
    echo "=== Configuring MCO boot image management ==="

    if ! oc get "${MACHINE_CONFIGURATION}" cluster &>/dev/null; then
        echo "  Error: ${MACHINE_CONFIGURATION}/cluster not found" >&2
        return 1
    fi

    label_machineset
    configure_managed_boot_images
    configure_boot_image_skew_enforcement
}

