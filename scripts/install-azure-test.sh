# ===================================================================
# Argument parsing and main
# ===================================================================
SOURCE_ONLY=false
declare -A SKIP_STEPS=()

parse_args() {
    while [[ $# -gt 0 ]]; do
        case $1 in
            --registry)         REGISTRY="$2"; shift 2 ;;
            --tag)              TAG="$2"; shift 2 ;;
            --approved-image)   APPROVED_IMAGE="$2"; shift 2 ;;
            --vhd-resource-id)  VHD_RESOURCE_ID="$2"; shift 2 ;;
            --source-machineset) SOURCE_MACHINESET="$2"; shift 2 ;;
            --namespace)        NAMESPACE="$2"; shift 2 ;;
            --machineset-name)  MACHINESET_NAME="$2"; shift 2 ;;
            --replicas)         REPLICAS="$2"; shift 2 ;;
            --vm-size)          VM_SIZE="$2"; shift 2 ;;
            --output-dir)       OUTPUT_DIR="$2"; shift 2 ;;
            --source-only)      SOURCE_ONLY=true; shift ;;
            --skip)             SKIP_STEPS["$2"]=1; shift 2 ;;
            -h|--help)          usage ;;
            *)                  echo "Unknown option: $1"; usage ;;
        esac
    done
}

validate_args() {
    for var in REGISTRY TAG APPROVED_IMAGE VHD_RESOURCE_ID SOURCE_MACHINESET; do
        if [[ -z "${!var}" ]]; then
            echo "Error: --$(echo $var | tr '[:upper:]' '[:lower:]' | tr '_' '-') is required"
            usage
        fi
    done

    # jq --argjson needs a number; catch a bad value here instead of at the
    # last step, after the whole deployment is already up.
    if [[ ! "${REPLICAS}" =~ ^[0-9]+$ ]]; then
        echo "Error: --replicas must be a non-negative integer, got '${REPLICAS}'" >&2
        exit 1
    fi

    require_cmds oc jq yq sed base64 kustomize make go python3

    if ! oc whoami &>/dev/null; then
        echo "Error: not connected to any cluster" >&2
        exit 1
    fi
}

run_all_steps() {
    local step_num=1
    local total=${#ALL_STEPS[@]}
    for step in "${ALL_STEPS[@]}"; do
        if [[ -n "${SKIP_STEPS[${step}]:-}" ]]; then
            echo ""
            echo "=== [${step_num}/${total}] Skipping ${step} ==="
        else
            echo ""
            echo "--- [${step_num}/${total}] ${step} ---"
            "${step}"
        fi
        step_num=$((step_num + 1))
    done
}

# ===================================================================
# Entry point
# ===================================================================
parse_args "$@"

if [[ "${SOURCE_ONLY}" == "true" ]]; then
    # Functions are defined; caller can invoke them directly.
    # Still validate if args were provided.
    if [[ -n "${REGISTRY}" ]]; then
        validate_args
    fi
    return 0 2>/dev/null || true
fi

validate_args
run_all_steps
