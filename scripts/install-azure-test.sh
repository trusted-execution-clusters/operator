# Deploys the trusted-execution-clusters operator on an Azure OpenShift cluster
# using the same method as the CI integration tests:
# - Direct manifest application (no OLM)
# - TLS via cert-manager
# - No AK registration (Azure vTPM does not support it)
# Then creates a confidential machineset and scales it up.
#
# Each step is a function. Run the script normally for all steps, or:
#   source install-azure-test.sh --source-only
# then call individual functions (e.g. step_install_cert_manager).

set -euo pipefail

# BASH_SOURCE, not $0: with --source-only $0 is the caller, which would
# resolve SCRIPT_DIR (and OPERATOR_DIR below) relative to the wrong directory.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OPERATOR_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"

# Manifests the steps apply. Everything below config/ except config/openshift
# is generated by step_generate_manifests and is not checked in, so the steps
# that read it only work after that step has run at least once.
# Absolute, so that every step works on its own: --skip and --source-only
# both let the caller run a step without step_generate_manifests.
CONFIG_DIR="${OPERATOR_DIR}/config"

# === Defaults ===
NAMESPACE="trusted-execution-clusters"
MACHINESET_NAME="conf-workers"
# 1, not 2: confidential VM SKUs have limited per-zone capacity, so the
# default asks Azure for as little as possible. Raise it with --replicas.
REPLICAS=1
VM_SIZE="Standard_DC4ads_v5"
REGISTRY=""
TAG=""
APPROVED_IMAGE=""
VHD_RESOURCE_ID=""
SOURCE_MACHINESET=""
MACHINE_API_NS="openshift-machine-api"
MACHINE_CONFIGURATION="machineconfigurations.operator.openshift.io"
# Where step_create_machineset writes the machineset it applies. Keep it out
# of the repository: the file is a record of the applied manifest, not source.
OUTPUT_DIR="/tmp"

# The label that keeps the MCO's boot image controller away from the
# confidential machineset. step_create_machineset applies it to the machineset
# it creates; step_configure_boot_image_management excludes every machineset
# that carries it.
BOOT_IMAGE_EXCLUDE_LABEL="custom-boot-image"

# === Derived variables (set after args are parsed) ===
MC_NAME=""
TRUSTEE_LB=""
TRUSTEE_ADDR=""
REG_SERVER_LB=""
REGISTRATION_SERVER=""
MANAGED_SECRET=""
IGNITION_SECRET=""
declare -A LB_ADDRS=()

usage() {
    cat <<EOF
Usage: $0 [options]

Required:
  --registry <registry>        Container registry (e.g. quay.io/myuser)
  --tag <tag>                  Operator version tag (e.g. v0.2.3)
  --approved-image <ref>       Bootable container image with sha256 digest, e.g.
                               quay.io/myuser/rhcos-confidential@sha256:abc123...
                               Get it with: skopeo inspect docker://<image>:<tag> --format '{{.Digest}}'
  --vhd-resource-id <id>       Azure VHD resource ID for machineset
  --source-machineset <name>   Existing worker machineset to base the conf machineset on

Optional:
  --namespace <ns>             Namespace (default: trusted-execution-clusters)
  --machineset-name <name>     Name for the new machineset (default: conf-workers)
  --replicas <n>               Number of replicas (default: 1)
  --vm-size <size>             Azure VM size (default: Standard_DC4ads_v5)
  --output-dir <dir>           Where to write the generated machineset YAML
                               (default: /tmp)
  --source-only                Parse args and define functions, but do not run steps
  --skip <step>                Skip a step by function name (repeatable)
  -h, --help                   Show this help
EOF
    exit 1
}

# ---------------------------------------------------------------------------
# Helper: fail early when a required command is missing
# ---------------------------------------------------------------------------
require_cmds() {
    local missing=()
    local cmd
    for cmd in "$@"; do
        if ! command -v "${cmd}" &>/dev/null; then
            missing+=("${cmd}")
        fi
    done
    if [ "${#missing[@]}" -ne 0 ]; then
        echo "Error: required command(s) not found: ${missing[*]}. Install them and ensure they are on PATH." >&2
        exit 1
    fi
}

# ---------------------------------------------------------------------------
# Helper: fail early when a generated manifest is missing
#
# config/crd, config/deploy and config/rbac/role.yaml are build output, not
# source: make manifests writes them and .gitignore excludes them. Skipping
# step_generate_manifests on a fresh checkout would otherwise fail with an oc
# "no such file" error that does not say what to run.
#
# Arguments may be globs, so the match test is compgen, not -f.
# ---------------------------------------------------------------------------
require_generated_manifests() {
    local pattern
    local missing=()
    for pattern in "$@"; do
        compgen -G "${pattern}" >/dev/null || missing+=("${pattern}")
    done
    if [ "${#missing[@]}" -ne 0 ]; then
        echo "Error: generated manifest(s) not found:" >&2
        printf '  %s\n' "${missing[@]}" >&2
        echo "Run step_generate_manifests (do not --skip it before the manifests exist)." >&2
        exit 1
    fi
}

# ---------------------------------------------------------------------------
# Helper: get LoadBalancer external address for a service
# ---------------------------------------------------------------------------
get_lb_address() {
    local svc=$1
    local addr=""
    echo "  Waiting for LoadBalancer address on ${svc}..." >&2
    until [ -n "${addr}" ]; do
        addr=$(oc get svc "${svc}" -n "${NAMESPACE}" -o jsonpath='{.status.loadBalancer.ingress[0].ip}' 2>/dev/null | tr -d '[:space:]')
        if [ -z "${addr}" ]; then
            addr=$(oc get svc "${svc}" -n "${NAMESPACE}" -o jsonpath='{.status.loadBalancer.ingress[0].hostname}' 2>/dev/null | tr -d '[:space:]')
        fi
        [ -z "${addr}" ] && sleep 5
    done
    echo "  ${svc} -> ${addr}" >&2
    printf '%s' "${addr}"
}

